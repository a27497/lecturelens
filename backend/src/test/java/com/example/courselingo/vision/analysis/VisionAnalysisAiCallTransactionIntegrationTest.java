    @Test
    void successfulFakeVisionTaskCreatesExactlyOneAccurateRecord() {
        state.keyframes = keyframes(2);

        VisionAnalysisScanResult result = service.scan("task_tx", 42L);

        assertThat(result.saved()).isEqualTo(2);
        assertThat(records()).singleElement().satisfies(record -> {
            assertThat(record.status()).isEqualTo(AiCallRecordStatus.SUCCEEDED);
            assertThat(record.batchCount()).isEqualTo(2);
            assertThat(record.inputUnits()).isEqualTo(2);
            assertThat(record.outputUnits()).isEqualTo(2);
            assertThat(record.providerDurationMillis()).isEqualTo(14L);
            assertThat(record.durationMillis()).isPositive();
        });
    }

    @Test
    void repeatableReadSnapshotCanCompleteRecordCreatedAfterSnapshot() {
        state.keyframes = keyframes(2);
        TransactionTemplate transaction = new TransactionTemplate(transactionManager);
        transaction.setIsolationLevel(TransactionDefinition.ISOLATION_REPEATABLE_READ);

        VisionAnalysisScanResult result = transaction.execute(status -> {
            assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM ai_call_record", Integer.class)).isZero();
            return service.scan("task_tx", 42L);
        });

        assertThat(result).isNotNull();
        assertThat(result.saved()).isEqualTo(2);
        assertThat(records()).singleElement().satisfies(record -> {
            assertThat(record.status()).isEqualTo(AiCallRecordStatus.SUCCEEDED);
            assertThat(record.inputUnits()).isEqualTo(2);
            assertThat(record.outputUnits()).isEqualTo(2);
        });
    }

    @Test
    void committedVisionRowsAndAuditAreIndependentFromACallerRollback() {
        state.keyframes = keyframes(2);
        TransactionTemplate transaction = new TransactionTemplate(transactionManager);

        transaction.executeWithoutResult(status -> {
            VisionAnalysisScanResult result = service.scan("task_tx", 42L);
            assertThat(result.saved()).isEqualTo(2);
            status.setRollbackOnly();
        });

        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM visual_probe", Integer.class)).isEqualTo(2);
        assertThat(records()).singleElement().satisfies(record ->
            assertThat(record.status()).isEqualTo(AiCallRecordStatus.SUCCEEDED)
        );
    }

    @Test
    void failedOuterVisionTransactionKeepsSanitizedFailedRecordAndRollsBackAnalysisRows() {
        state.keyframes = keyframes(1);
        state.failAnalysisInsert = true;

        assertThatThrownBy(() -> service.scan("task_tx", 42L))
            .isInstanceOf(IllegalStateException.class);

        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM visual_probe", Integer.class)).isZero();
        assertThat(records()).singleElement().satisfies(record -> {
            assertThat(record.status()).isEqualTo(AiCallRecordStatus.FAILED);
            assertThat(record.durationMillis()).isPositive();
            assertThat(record.errorCode()).isEqualTo("VISION_ANALYSIS_FAILED");
            assertThat(record.errorMessage()).doesNotContain("objectKey", "token", "C:\\");
        });
    }

    @Test
    void oneFailedFrameProducesPartialSuccessWithFiveAttemptedAndFourOutputs() {
        state.keyframes = keyframes(5);
        state.providerFailureKeyframeId = 3L;

        VisionAnalysisScanResult result = service.scan("task_tx", 42L);

        assertThat(result.saved()).isEqualTo(5);
        assertThat(result.succeeded()).isEqualTo(4);
        assertThat(result.failed()).isEqualTo(1);
        assertThat(records()).singleElement().satisfies(record -> {
            assertThat(record.status()).isEqualTo(AiCallRecordStatus.PARTIAL_SUCCESS);
            assertThat(record.batchCount()).isEqualTo(5);
            assertThat(record.inputUnits()).isEqualTo(5);
            assertThat(record.outputUnits()).isEqualTo(4);
            assertThat(record.providerDurationMillis()).isEqualTo(28L);
        });
    }

    private List<AiCallRecordView> records() {
        return jdbc.query("SELECT * FROM ai_call_record ORDER BY id", (rs, rowNum) -> new AiCallRecordView(
            rs.getLong("id"), rs.getString("task_id"),
            com.example.courselingo.ai.record.domain.AiCallType.valueOf(rs.getString("call_type")),
            com.example.courselingo.ai.record.domain.AiCallStage.valueOf(rs.getString("stage")),
            rs.getString("provider"), rs.getString("model"),
            AiCallRecordStatus.valueOf(rs.getString("status")),
            rs.getTimestamp("started_at").toLocalDateTime(),
            rs.getTimestamp("finished_at") == null ? null : rs.getTimestamp("finished_at").toLocalDateTime(),
            nullableLong(rs, "duration_millis"), nullableLong(rs, "provider_duration_millis"),
            nullableInt(rs, "batch_count"), nullableInt(rs, "retry_count"),
            nullableInt(rs, "prompt_tokens"), nullableInt(rs, "completion_tokens"),
            nullableInt(rs, "total_tokens"), nullableInt(rs, "input_units"), nullableInt(rs, "output_units"),
            rs.getString("request_fingerprint"), rs.getString("response_fingerprint"),
            rs.getString("error_code"), rs.getString("error_message"),
            rs.getObject("retryable", Boolean.class),
            rs.getTimestamp("created_at").toLocalDateTime(), rs.getTimestamp("updated_at").toLocalDateTime()
        ));
    }

    private static Long nullableLong(java.sql.ResultSet rs, String column) throws java.sql.SQLException {
        long value = rs.getLong(column);
        return rs.wasNull() ? null : value;
    }

    private static Integer nullableInt(java.sql.ResultSet rs, String column) throws java.sql.SQLException {
        int value = rs.getInt(column);
        return rs.wasNull() ? null : value;
    }

    private static List<VideoKeyframe> keyframes(int count) {
        List<VideoKeyframe> result = new ArrayList<>();
        for (int index = 0; index < count; index++) {
            VideoKeyframe keyframe = new VideoKeyframe();
            keyframe.setId((long) index + 1L);
            keyframe.setTaskId("task_tx");
            keyframe.setUserId(42L);
            keyframe.setFrameIndex(index);
            keyframe.setTimestampMillis(index * 60_000L);
            keyframe.setSelectReason(KeyframeSelectionReason.CONTENT_CHANGE.name());
            keyframe.setObjectKey("fictional-frame-" + index);
            result.add(keyframe);
        }
        return result;
    }

