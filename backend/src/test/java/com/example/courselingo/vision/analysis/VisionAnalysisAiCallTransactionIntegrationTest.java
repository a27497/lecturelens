    static final class FakeVisionState {
        private List<VideoKeyframe> keyframes = List.of();
        private Long providerFailureKeyframeId;
        private boolean failAnalysisInsert;

        private void reset() {
            keyframes = List.of();
            providerFailureKeyframeId = null;
            failAnalysisInsert = false;
        }
    }
