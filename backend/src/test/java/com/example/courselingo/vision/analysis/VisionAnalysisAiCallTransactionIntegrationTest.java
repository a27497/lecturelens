        @Bean
        AiCallRecordMapper aiCallRecordMapper(JdbcTemplate jdbc) {
            AiCallRecordMapper mapper = mock(AiCallRecordMapper.class);
            AtomicLong ids = new AtomicLong();
            when(mapper.insert(any(AiCallRecord.class))).thenAnswer(invocation -> {
                AiCallRecord row = invocation.getArgument(0);
                long id = ids.incrementAndGet();
                row.setId(id);
                return jdbc.update("""
                    INSERT INTO ai_call_record (
                      id, task_id, user_id, call_type, stage, provider, model, status, started_at,
                      input_units, request_fingerprint, created_at, updated_at
                    ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                    """, id, row.getTaskId(), row.getUserId(), row.getCallType(), row.getStage(),
                    row.getProvider(), row.getModel(), row.getStatus(), row.getStartedAt(), row.getInputUnits(),
                    row.getRequestFingerprint(), row.getCreatedAt(), row.getUpdatedAt());
            });
            when(mapper.selectByIdTaskIdAndUserId(any(), any(), any())).thenAnswer(invocation -> {
                List<AiCallRecord> rows = jdbc.query(
                    "SELECT * FROM ai_call_record WHERE id=? AND task_id=? AND user_id=?",
                    (rs, rowNum) -> recordFrom(rs), invocation.getArgument(0), invocation.getArgument(1),
                    invocation.getArgument(2));
                return rows.isEmpty() ? null : rows.getFirst();
            });
            when(mapper.updateByIdTaskIdAndUserId(any(), any(), any(), any())).thenAnswer(invocation -> {
                AiCallRecord row = invocation.getArgument(0);
                return jdbc.update("""
                    UPDATE ai_call_record SET status=?, finished_at=?, duration_millis=?,
                      provider_duration_millis=COALESCE(?, provider_duration_millis),
                      batch_count=COALESCE(?, batch_count), retry_count=COALESCE(?, retry_count),
                      prompt_tokens=COALESCE(?, prompt_tokens), completion_tokens=COALESCE(?, completion_tokens),
                      total_tokens=COALESCE(?, total_tokens), input_units=COALESCE(?, input_units),
                      output_units=COALESCE(?, output_units), request_fingerprint=COALESCE(?, request_fingerprint),
                      response_fingerprint=COALESCE(?, response_fingerprint), error_code=?, error_message=?,
                      retryable=?, updated_at=? WHERE id=? AND task_id=? AND user_id=?
                    """, row.getStatus(), row.getFinishedAt(), row.getDurationMillis(),
                    row.getProviderDurationMillis(), row.getBatchCount(), row.getRetryCount(),
                    row.getPromptTokens(), row.getCompletionTokens(), row.getTotalTokens(), row.getInputUnits(),
                    row.getOutputUnits(), row.getRequestFingerprint(), row.getResponseFingerprint(),
                    row.getErrorCode(), row.getErrorMessage(), row.getRetryable(), row.getUpdatedAt(),
                    invocation.getArgument(1), invocation.getArgument(2), invocation.getArgument(3));
            });
            return mapper;
        }

        @Bean
        AiCallRecordService aiCallRecordService(AiCallRecordMapper mapper) {
            return new AiCallRecordServiceImpl(mapper, Clock.systemUTC(), new AiCallRecordSanitizer());
        }

        @Bean
        VisionAnalysisService visionAnalysisService(
            JdbcTemplate jdbc,
            FakeVisionState state,
            AiCallRecordService records,
            PlatformTransactionManager transactionManager
        ) {
            VideoKeyframeMapper keyframes = mock(VideoKeyframeMapper.class);
            when(keyframes.selectByTaskIdAndUserId(any(), any())).thenAnswer(ignored -> state.keyframes);
            VideoKeyframeOcrMapper ocr = mock(VideoKeyframeOcrMapper.class);
            when(ocr.selectByKeyframeIds(any(), any(), any())).thenReturn(List.<VideoKeyframeOcr>of());
            VideoKeyframeAnalysisMapper analyses = mock(VideoKeyframeAnalysisMapper.class);
            when(analyses.deleteByTaskIdAndUserId(any(), any())).thenAnswer(ignored -> jdbc.update("DELETE FROM visual_probe"));
            when(analyses.insert(any(VideoKeyframeAnalysis.class))).thenAnswer(invocation -> {
                VideoKeyframeAnalysis row = invocation.getArgument(0);
                int inserted = jdbc.update("INSERT INTO visual_probe (keyframe_id, status) VALUES (?, ?)",
                    row.getKeyframeId(), row.getStatus());
                if (state.failAnalysisInsert) {
                    throw new IllegalStateException("fictional persistence failure");
                }
                return inserted;
            });
            StorageService storage = mock(StorageService.class);
            when(storage.openObject(any())).thenReturn(new ByteArrayInputStream(
                "fictional image".getBytes(StandardCharsets.UTF_8)));
            VisionModelProvider provider = new VisionModelProvider() {
                @Override
                public String providerName() {
                    return "fake-vision";
                }

                @Override
                public VisionAnalysisResult analyze(VisionAnalysisRequest request) {
                    if (request.keyframeId().equals(state.providerFailureKeyframeId)) {
                        throw new IllegalStateException("fictional provider failure");
                    }
                    return new VisionAnalysisResult(
                        VisionAnalysisStatus.SUCCEEDED, "PPT", "fictional summary", List.of("title"),
                        providerName(), request.route().modelName(), 7L, null, null
                    );
                }
            };
            AiModelRouter router = mock(AiModelRouter.class);
            when(router.route(AiModelStage.VISION_FRAME_ANALYSIS)).thenReturn(new AiModelRoute(
                AiModelStage.VISION_FRAME_ANALYSIS, "fake", "Fake", "fake-vision", "https://invalid.test",
                "fictional-vl", "TEST_ONLY", EnumSet.of(ModelCapability.VISION, ModelCapability.JSON_OUTPUT),
                0.0d, 256, Duration.ofSeconds(1), 1
            ));
            VisionAnalysisProperties properties = new VisionAnalysisProperties();
            properties.setEnabled(true);
            properties.setMaxFramesTotal(10);
            properties.setMaxFramesPerMinute(10);
            properties.setSlideMaxFramesPerMinute(10);
            properties.setCodeOrTerminalMaxFramesPerMinute(10);
            properties.setVisualDemoMaxFramesPerMinute(10);
            properties.setTalkingOrLowInformationMaxFramesPerMinute(10);
            properties.setUnknownMaxFramesPerMinute(10);
            return new VisionAnalysisServiceImpl(
                keyframes, ocr, analyses, storage, provider, router, new HighValueKeyframeSelector(), properties,
                new ObjectMapper(), Clock.systemUTC(), null, null, records, transactionManager
            );
        }

        private static AiCallRecord recordFrom(java.sql.ResultSet rs) throws java.sql.SQLException {
            AiCallRecord row = new AiCallRecord();
            row.setId(rs.getLong("id"));
            row.setTaskId(rs.getString("task_id"));
            row.setUserId(rs.getLong("user_id"));
            row.setCallType(rs.getString("call_type"));
            row.setStage(rs.getString("stage"));
            row.setProvider(rs.getString("provider"));
            row.setModel(rs.getString("model"));
            row.setStatus(rs.getString("status"));
            row.setStartedAt(rs.getTimestamp("started_at").toLocalDateTime());
            row.setCreatedAt(rs.getTimestamp("created_at").toLocalDateTime());
            row.setUpdatedAt(rs.getTimestamp("updated_at").toLocalDateTime());
            return row;
        }
